import fs from "fs";
import path from "path";
import sharp from "sharp";

const IMAGES_DIR = path.resolve("public/images");
const OUT_FILE = path.resolve("src/data/image-manifest.generated.ts");

function getAllFiles(dir, fileList = []) {
  if (!fs.existsSync(dir)) return fileList;
  const files = fs.readdirSync(dir);
  for (const file of files) {
    const fullPath = path.join(dir, file);
    if (fs.statSync(fullPath).isDirectory()) {
      getAllFiles(fullPath, fileList);
    } else if (/\.(webp|jpg|jpeg|png|avif)$/i.test(file)) {
      fileList.push(fullPath);
    }
  }
  return fileList;
}

export async function generateManifest() {
  const files = getAllFiles(IMAGES_DIR);
  const manifest = {};

  // Sort files for deterministic output
  files.sort();

  for (const filePath of files) {
    const relFromPublic = "/" + path.relative(path.resolve("public"), filePath).replace(/\\/g, "/");
    const basename = path.basename(filePath, path.extname(filePath));

    // Handle optional responsive variants: <key>-480, <key>-960, <key>-1600
    const variantMatch = basename.match(/^(.+)-(480|960|1600)$/);
    const key = variantMatch ? variantMatch[1] : basename;

    try {
      const metadata = await sharp(filePath).metadata();
      const stats = fs.statSync(filePath);

      if (!manifest[key]) {
        manifest[key] = {
          src: relFromPublic,
          width: metadata.width || 1200,
          height: metadata.height || 800,
          bytes: stats.size,
          variants: [],
        };
      }

      if (variantMatch) {
        const width = parseInt(variantMatch[2], 10);
        manifest[key].variants.push({ src: relFromPublic, width });
      }
    } catch (e) {
      console.warn(`Could not read dimensions for ${filePath}:`, e.message);
    }
  }

  // Format srcSet if variants exist
  for (const key of Object.keys(manifest)) {
    if (manifest[key].variants?.length > 0) {
      manifest[key].variants.sort((a, b) => a.width - b.width);
      manifest[key].srcSet = manifest[key].variants
        .map((v) => `${v.src} ${v.width}w`)
        .join(", ");
    }
    delete manifest[key].variants;
  }

  // Generate TypeScript code
  const code = `// Auto-generated by scripts/generate-image-manifest.mjs
// Do not edit manually. Re-run "npm run generate:manifest" or prebuild.

export interface ImageManifestEntry {
  src: string;
  srcSet?: string;
  width: number;
  height: number;
  bytes: number;
}

export const imageManifest: Record<string, ImageManifestEntry> = ${JSON.stringify(
    manifest,
    null,
    2
  )};
`;

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, code, "utf-8");
  console.log(`✓ Image manifest generated with ${Object.keys(manifest).length} entries at ${OUT_FILE}`);
}

generateManifest().catch((err) => {
  console.error("Error generating manifest:", err);
  process.exit(1);
});
